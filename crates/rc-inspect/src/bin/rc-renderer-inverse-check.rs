use rc_package::{
    renderer_inverse::Input as Math, renderer_inverse_draw::Request,
    renderer_transform::RendererRuntime as Runtime,
};
use serde::Deserialize;
use std::{env, fs};
#[derive(Deserialize)]
struct Case {
    id: usize,
    runtime: Runtime,
    requests: Vec<Request>,
}
#[derive(Deserialize)]
struct Input {
    source_sha256: String,
    math: Vec<Math>,
    passes_sha256: String,
    cases: Vec<Case>,
    errors: Vec<Case>,
}
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args: Vec<_> = env::args().collect();
    if args.len() != 3 {
        return Err("Expected INPUT OUTPUT".into());
    }
    let input: Input = serde_json::from_slice(&fs::read(&args[1])?)?;
    let math: Vec<_> = input
        .math
        .iter()
        .map(|q| rc_package::renderer_inverse::scalar53(q.matrix, q.store_determinant))
        .collect();
    let (mut probes, mut errors) = (vec![], vec![]);
    for (safe, cases) in [(false, input.cases), (true, input.errors)] {
        for c in cases {
            let mut rt = c.runtime;
            let mut steps = vec![];
            for mut q in c.requests {
                let result = rt.submit_scalar53(&mut q);
                if !safe {
                    if let Err(e) = &result {
                        return Err(e.clone().into());
                    }
                }
                steps.push(serde_json::json!({"result":result,"runtime":rt,"request":q}));
            }
            let value = serde_json::json!({"id":c.id,"steps":steps,"runtime":rt});
            if safe {
                errors.push(value);
            } else {
                probes.push(value);
            }
        }
    }
    fs::write(
        &args[2],
        serde_json::to_vec(
            &serde_json::json!({"source_sha256":input.source_sha256,"passes_sha256":input.passes_sha256,"math":math,"probes":probes,"errors":errors,"scope":"Computed original scalar inverse under explicit nearest x87 precision53, including f32 spills, optional determinant and finite reciprocal write gate; joined renderer/mesh CPU path. Independent rational precision53 replay. CPU-optimized variants/precision64 and live GPU/Android excluded."}),
        )?,
    )?;
    Ok(())
}
