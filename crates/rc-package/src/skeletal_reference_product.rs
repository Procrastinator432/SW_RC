//! Generated from original reference-parent scalar SSE expressions.
pub fn compose_reference_matrix(local: [u32; 16], parent: [u32; 16]) -> [u32; 16] {
    let m = local.map(f32::from_bits);
    let p = parent.map(f32::from_bits);
    [
        ((((p[8] * m[2]) + (p[4] * m[1])) + (p[0] * m[0])) + (m[3] * p[12])),
        ((((p[13] * m[3]) + (p[5] * m[1])) + (p[1] * m[0])) + (p[9] * m[2])),
        ((((m[3] * p[14]) + (p[6] * m[1])) + (p[2] * m[0])) + (p[10] * m[2])),
        ((((m[0] * p[3]) + (p[11] * m[2])) + (p[15] * m[3])) + (p[7] * m[1])),
        ((((p[8] * m[6]) + (p[0] * m[4])) + (m[7] * p[12])) + (p[4] * m[5])),
        ((((p[1] * m[4]) + (m[5] * p[5])) + (m[7] * p[13])) + (m[6] * p[9])),
        ((((p[2] * m[4]) + (m[7] * p[14])) + (m[6] * p[10])) + (m[5] * p[6])),
        ((((p[15] * m[7]) + (p[11] * m[6])) + (m[5] * p[7])) + (p[3] * m[4])),
        ((((p[8] * m[10]) + (p[0] * m[8])) + (m[11] * p[12])) + (p[4] * m[9])),
        ((((p[1] * m[8]) + (m[9] * p[5])) + (m[11] * p[13])) + (m[10] * p[9])),
        ((((p[2] * m[8]) + (m[11] * p[14])) + (m[10] * p[10])) + (m[9] * p[6])),
        ((((p[15] * m[11]) + (p[11] * m[10])) + (m[9] * p[7])) + (p[3] * m[8])),
        ((((p[8] * m[14]) + (p[0] * m[12])) + (m[15] * p[12])) + (m[13] * p[4])),
        ((((m[13] * p[5]) + (p[1] * m[12])) + (m[15] * p[13])) + (m[14] * p[9])),
        ((((m[15] * p[14]) + (m[14] * p[10])) + (p[2] * m[12])) + (m[13] * p[6])),
        ((((p[15] * m[15]) + (p[11] * m[14])) + (m[13] * p[7])) + (p[3] * m[12])),
    ]
    .map(f32::to_bits)
}
